export class I18n {
  constructor(private readonly all: Record<string, Catalog> = catalogs) {}

  /** Mensaje en `lang`; si falta el idioma o la clave, usa español. */
  t(key: MessageKey, lang?: string | null, params: Record<string, string | number> = {}): string {
    const raw = (lang ? this.all[lang]?.[key] : undefined) ?? this.all[DEFAULT_LANGUAGE]?.[key] ?? es[key];
    return raw.replace(/\{(\w+)\}/g, (m, name: string) =>
      name in params ? String(params[name]) : m,
    );
  }
}
